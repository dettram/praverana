def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--version", default="v0.1")
    args = ap.parse_args()

    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    doc = Document()
    base.setup(doc)
    base.footer(doc, f"{OBJ['code']} · ППР-КМ {args.version}")
    build(doc, args.version)
    path = out / f"{DOC_CODE}-{args.version}.docx"
    doc.save(str(path))
    print(f"written: {path}")
    print(f"truss={f(TRUSS_MASS)} t, total_steel={f(TOTAL_STEEL)} t, deck={f(DECK_MASS)} t, "
          f"req_cap={f(REQ_CAP * 1.1, 1)} t")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

