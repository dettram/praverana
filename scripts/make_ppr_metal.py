# ---- исходные для расчёта масс (все — оценка, спецификация КМ отсутствует) ----
TRUSS_L, TRUSS_STEP = 36.0, 6.0          # м
TRUSS_RATE = 35.0                        # кг/м² покрытия — принято
COL_QTY, COL_MASS = 32, 2.4              # шт., т
BRACE_MASS = 12.0                        # т
DECK_AREA, DECK_RATE = 36.0 * 48.0, 9.6  # м², кг/м² (Н75-750-0,9)
BRIDGE_QTY, BRIDGE_MASS = 2, 4.5         # шт., т
TRAVERSE_MASS = 0.6                      # т, траверса/строп

TRUSS_AREA = TRUSS_L * TRUSS_STEP
TRUSS_MASS = TRUSS_AREA * TRUSS_RATE / 1000
TRUSS_QTY = int(round(48 / TRUSS_STEP))  # 8 ферм на корпус Б
DECK_MASS = DECK_AREA * DECK_RATE / 1000
TOTAL_STEEL = (TRUSS_MASS * TRUSS_QTY + COL_QTY * COL_MASS + BRACE_MASS
               + BRIDGE_QTY * BRIDGE_MASS)
REQ_CAP = TRUSS_MASS + TRAVERSE_MASS


def f(x: float, nd: int = 2) -> str:
    return f"{x:.{nd}f}".replace(".", ",")


