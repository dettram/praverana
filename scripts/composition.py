"""Общая проверка состава ПОС/ППР по СН 1.03.04-2020.

Шифры пунктов — не единственный признак: реальные документы называют разделы
словами. Поэтому база проверяется по заголовкам, а специальные разделы
(реконструкция, линейные объекты, гидротехника, геодезия, снос) — только при
соответствующем типе объекта.
"""
from __future__ import annotations

POS_BASE = {
    "Г.7": ("пояснительн",),
    "Г.8": ("календарн",),
    "Г.9": ("генеральный план", "стройгенплан"),
    "Г.10": ("организационно-технологич", "организационно-технологическ"),
    "Г.11": ("строительных машин", "машин и транспорт"),
    "Г.12": ("потребности в кадрах", "численности работников", "кадр"),
}

PPR_BASE = {
    "В.1": ("календарн", ("генеральный план", "стройгенплан"), "технологическ",
            ("охрана труда", "охране труда"), "пояснительн"),
    "В.2": ("календарн", ("генеральный план", "стройгенплан"), "технологическ",
            "пояснительн"),
    "В.3": ("календарн", ("генеральный план", "стройгенплан"), "график движения",
            "пояснительн"),
}

# clause -> (признаки типа объекта, признаки специального раздела)
PPR_SPECIAL = {
    "В.5": (("реконструкц", "капитальн"), ("эксплуатируем", "действующ", "остановк")),
    "В.6": (("линейн", "трубопровод", "железнодорож", "лэп"),
            ("трасс", "переход", "транспортн")),
    "В.7": (("гидротех", "водохозяйств"), ("гидроэлектр", "перемычк", "русл")),
    "В.8": (("геодез",), ("разбивочн", "деформац", "съемк")),
    "В.10": (("снос", "демонтаж"), ("отход", "пыл", "складирован")),
    "В.11": (("снос", "демонтаж"), ("последовательность сноса", "опасных зон",
                                      "утилизац")),
}


def _keywords(value):
    for item in value:
        if isinstance(item, tuple):
            yield from item
        else:
            yield item


def _has(low: str, clause: str, keywords) -> bool:
    if clause.lower() in low:
        return True
    return any(word in low for word in _keywords(keywords))


def _ppr_kind(low: str, name: str) -> str:
    name = (name or "").lower()
    if "-км" in name or "монтаж" in name or "отдельных видов работ" in low:
        return "В.2"
    if "подготовительн" in low or "подготовительн" in name:
        return "В.3"
    return "В.1"


def missing_sections(kind: str, text: str, name: str = "") -> list[str]:
    """Список отсутствующих обязательных пунктов приложения."""
    low = " ".join((text or "").lower().split())
    if kind == "pos":
        required = dict(POS_BASE)
    elif kind == "ppr":
        sub = _ppr_kind(low, name)
        required = {sub: PPR_BASE[sub]}
        for clause, (triggers, keywords) in PPR_SPECIAL.items():
            if any(trigger in low for trigger in triggers):
                required[clause] = keywords
    else:
        return []
    return [clause for clause, keywords in required.items()
            if not _has(low, clause, keywords)]
