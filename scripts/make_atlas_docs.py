def para(doc: Document, text: str, bold: bool = False, italic: bool = False,
         size: int | None = None, align=None, indent: bool = True) -> None:
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.name = "Times New Roman"
    run.bold = bold
    run.italic = italic
    if size:
        run.font.size = Pt(size)
    if align is not None:
        p.alignment = align
    if not indent:
        p.paragraph_format.first_line_indent = Cm(0)
    return None


CITED: set[str] = set()


def basis(doc: Document, codes) -> None:
    """Строка «Нормативное основание» под заголовком раздела."""
    for c in codes:
        CITED.add(c.split(",")[0].split(" (")[0].strip())
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.space_after = Pt(6)
    run = p.add_run("Нормативное основание: " + "; ".join(codes) + ".")
    run.font.name = "Times New Roman"
    run.font.size = Pt(11)
    run.italic = True


def bullets(doc: Document, items) -> None:
    for it in items:
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(1.25)
        p.paragraph_format.first_line_indent = Cm(-0.6)
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
        p.paragraph_format.tab_stops.add_tab_stop(Cm(1.25))
        run = p.add_run("•\t" + it)
        run.font.name = "Times New Roman"
        run.font.size = Pt(14)


def table(doc: Document, headers, rows, widths=None, size: float = 8.5,
          caption: str | None = None) -> None:
    if caption:
        p = doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.space_before = Pt(6)
        run = p.add_run(caption)
        run.font.name = "Times New Roman"
        run.font.size = Pt(11)
        run.italic = True
    tbl = doc.add_table(rows=1, cols=len(headers))
    tbl.style = "Table Grid"
    tbl.autofit = False
    tr_pr = tbl.rows[0]._tr.get_or_add_trPr()
    tr_pr.append(OxmlElement("w:tblHeader"))
    for i, text in enumerate(headers):
        cell = tbl.rows[0].cells[i]
        cell.text = ""
        run = cell.paragraphs[0].add_run(str(text))
        run.font.name = "Times New Roman"
        run.font.size = Pt(size)
        run.bold = True
        cell.paragraphs[0].paragraph_format.first_line_indent = Cm(0)
        cell.paragraphs[0].paragraph_format.line_spacing = 1.0
        cell.paragraphs[0].paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
        if widths:
            cell.width = Cm(widths[i])
    for row in rows:
        cells = tbl.add_row().cells
        for i, text in enumerate(row):
            cells[i].text = ""
            run = cells[i].paragraphs[0].add_run(str(text))
            run.font.name = "Times New Roman"
            run.font.size = Pt(size)
            cells[i].paragraphs[0].paragraph_format.first_line_indent = Cm(0)
            cells[i].paragraphs[0].paragraph_format.line_spacing = 1.0
            cells[i].paragraphs[0].paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
            if widths:
                cells[i].width = Cm(widths[i])
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def note(doc: Document, text: str) -> None:
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(0)
    run = p.add_run(text)
    run.font.name = "Times New Roman"
    run.italic = True
    run.font.size = Pt(11)


def toc(doc: Document) -> None:
    para(doc, "СОДЕРЖАНИЕ", bold=True, size=14, align=WD_ALIGN_PARAGRAPH.CENTER, indent=False)
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(0)
    _field_run(p, 'TOC \\o "1-2" \\h \\z \\u',
               "Оглавление собирается автоматически при открытии документа (F9).", size=12)
    doc.add_page_break()


