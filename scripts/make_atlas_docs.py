def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--version", default="v0.2")
    args = ap.parse_args()

    if not NORMS.exists():
        print("нет data/norms-pos.json — сначала build_norms_list.py", file=sys.stderr)
        return 2
    data = load_norms()

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    sgp = out_dir / "СГП" / f"{OBJ['code']}-СГП-01.png"

    for kind, name, builder in (("pos", "ПОС", build_pos), ("ppr", "ППР", build_ppr)):
        doc = Document()
        setup(doc)
        footer(doc, f"{OBJ['code']} · {name} {args.version}")
        if kind == "pos":
            builder(doc, args.version, data, sgp)
        else:
            builder(doc, args.version, data)
        out = out_dir / f"{OBJ['code']}-{name}-{args.version}.docx"
        doc.save(str(out))
        print(f"written: {out}")

    index = {it["code"] for g in data["groups"] for it in g["items"]}
    unknown = sorted(CITED - index)
    if unknown:
        print("ВНИМАНИЕ: нормы упомянуты в тексте, но отсутствуют в приложении А: "
              + "; ".join(unknown))
    print(f"cited={len(CITED & index)}/{len(index)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


