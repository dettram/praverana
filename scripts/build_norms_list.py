def load_registry(corpus: Path) -> dict[str, dict]:
    reg = corpus / "02-Реестр.csv"
    out: dict[str, dict] = {}
    with reg.open(encoding="utf-8-sig", newline="") as fh:
        for r in csv.DictReader(fh, delimiter=";"):
            r = {k.strip(): (v or "").strip() for k, v in r.items()}
            code = r.get("Шифр", "")
            if code:
                out[code] = r
    return out


def load_docs() -> dict[str, int]:
    if not DB.exists():
        return {}
    db = sqlite3.connect(str(DB))
    rows = db.execute("SELECT code, COUNT(*) FROM docs WHERE code IS NOT NULL GROUP BY code").fetchall()
    db.close()
    return {c: n for c, n in rows}


def main() -> int:
    corpus = Path(CORPUS_DEFAULT)
    registry = load_registry(corpus)
    docs = load_docs()

    data = {"source": "02-Реестр.csv (состояние на 18.11.2026) + индекс .stroy-audit", "groups": []}
    seen: set[str] = set()
    missing: list[str] = []

    for key, title, codes in GROUPS:
        items = []
        for code in codes:
            rec = registry.get(code)
            if rec is None:
                missing.append(code)
                items.append({
                    "code": code, "name": "", "status": "нет в реестре",
                    "file": "—", "note": "статус не подтверждён — проверить",
                })
                continue
            status = rec.get("Статус на 18.11.2026", "")
            n = docs.get(code, 0)
            items.append({
                "code": code,
                "name": rec.get("Наименование", ""),
                "status": status,
                "file": "есть" if n else "нет",
                "note": rec.get("Заменяет / чем заменён", ""),
            })
            seen.add(code)
        data["groups"].append({"key": key, "title": title, "items": items})

    (SKILL / "data").mkdir(exist_ok=True)
    (SKILL / "data" / "norms-pos.json").write_text(
        json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")

    md = ["# Перечень ТНПА для ПОС/ППР", "",
          "Источники: `02-Реестр.csv` (18.11.2026), индекс `.stroy-audit/index.sqlite`.", ""]
    total = 0
    for g in data["groups"]:
        md += [f"## {g['title']}", "", "| Шифр | Наименование | Статус | Файл |", "|---|---|---|---|"]
        for it in g["items"]:
            total += 1
            md.append(f"| {it['code']} | {it['name'] or '—'} | {it['status']} | {it['file']} |")
        md.append("")
    (SKILL / "data" / "norms-pos.md").write_text("\n".join(md) + "\n", encoding="utf-8")

    print(f"groups={len(data['groups'])} codes={total} not_in_registry={len(missing)}")
    if missing:
        print("нет в реестре:", "; ".join(missing))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

